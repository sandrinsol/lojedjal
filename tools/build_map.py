#!/usr/bin/env python3
"""Turns a map text file into the ROM map block (include/gen/septem_map.h).

Map text, one row per line, all rows the same width (8..32), 8..32 rows:
  #  wall            W  wall with a lancet window
  .  floor           ^ > v <  the start, facing north / east / south / west

The block starts with the magic "SEPTMAP1" so the web map editor can find it
in septem.gba and patch a new layout in without rebuilding (web/editor.html).
Layout: magic[8], width, height, start_x, start_y, facing, pad[3], cells[1024].
"""

import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FACINGS = {'^': 0, '>': 1, 'v': 2, '<': 3}
MAX = 32


def parse(text):
    rows = [r.rstrip('\r') for r in text.strip('\n').split('\n') if r.strip()]
    if not 8 <= len(rows) <= MAX:
        raise ValueError(f'{len(rows)} rows: a map has 8 to {MAX} rows')
    width = len(rows[0])
    if not 8 <= width <= MAX:
        raise ValueError(f'width {width}: a map is 8 to {MAX} cells wide')
    start = None
    cells = []
    for y, row in enumerate(rows):
        if len(row) != width:
            raise ValueError(f'row {y + 1} is {len(row)} wide, expected {width}')
        for x, ch in enumerate(row):
            if ch in FACINGS:
                if start:
                    raise ValueError('more than one start (^ > v <)')
                start = (x, y, FACINGS[ch])
                ch = '.'
            if ch not in '#W.':
                raise ValueError(f'unknown cell {ch!r} at row {y + 1}, column {x + 1}')
            cells.append(ch)
    if not start:
        raise ValueError('no start: mark it with ^ > v or <')
    return width, len(rows), start, ''.join(cells)


def main():
    src = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, 'maps', 'drowned_abbey.txt')
    width, height, (sx, sy, facing), cells = parse(open(src).read())
    out = os.path.join(ROOT, 'include', 'gen', 'septem_map.h')
    chunks = [cells[i:i + width] for i in range(0, len(cells), width)]
    body = '\n'.join(f'            "{c}"' for c in chunks)
    with open(out, 'w') as fh:
        fh.write(f'''// Generated by tools/build_map.py from {os.path.relpath(src, ROOT)}. Do not edit.
#ifndef SEPTEM_MAP_GEN_H
#define SEPTEM_MAP_GEN_H

#include "septem_level.h"

namespace septem::gen
{{
    // In its own section and marked used: the web map editor finds the magic
    // in the ROM and patches the layout in place.
    __attribute__((used, section(".rodata.septem_map"))) inline constexpr map_block stage_map = {{
        {{ 'S', 'E', 'P', 'T', 'M', 'A', 'P', '1' }},
        {width}, {height}, {sx}, {sy}, {facing}, {{ 0, 0, 0 }},
        {{
{body}
        }}
    }};
}}

#endif
''')
    print(f'{os.path.relpath(src, ROOT)}: {width}x{height}, start {sx},{sy} facing {"NESW"[facing]}')


if __name__ == '__main__':
    main()
